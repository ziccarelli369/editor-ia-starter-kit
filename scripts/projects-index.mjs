#!/usr/bin/env node
// Rebuild PROJECTS.md from every video-projects/*/project.json.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'video-projects');
const rows = [];
for (const name of readdirSync(dir).sort().reverse()) {
  const file = join(dir, name, 'project.json');
  if (!existsSync(file)) continue;
  const p = JSON.parse(readFileSync(file, 'utf8'));
  const outbox = join(root, 'outbox', p.id);
  const delivered = existsSync(outbox) ? readdirSync(outbox).filter(f => /\.(mp4|mov|webm)$/i.test(f)).length : 0;
  rows.push(`| ${p.id} | ${p.brand} | ${p.mode} | ${p.status} | ${p.style ?? '-'} | ${delivered} | ${p.notes || ''} |`);
}
const header = '# Projects\n\nGenerated by `npm run projects`. Do not edit; edit each project.json.\n\n| Project | Brand | Mode | Status | Style | Delivered | Notes |\n| --- | --- | --- | --- | --- | --- | --- |\n';
writeFileSync(join(root, 'PROJECTS.md'), header + rows.join('\n') + '\n');
console.log(`${rows.length} projects indexed in PROJECTS.md`);
